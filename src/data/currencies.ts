// Helper to calculate simulated quote variance
export function calculateSpreadRate(
  baseRate: number,
  channel: 'interbank' | 'moneychanger' | 'creditcard' | 'travelcard'
): { rate: number; feePercent: number; label: string } {
  switch (channel) {
    case 'interbank':
      return { rate: baseRate, feePercent: 0.0, label: 'Interbank Mid-Market (0% Markup)' };
    case 'moneychanger':
      // The Arcade / Mustafa Money Changers typically offer ~0.4% - 0.7% spread
      return { rate: baseRate * 0.994, feePercent: 0.6, label: 'Physical Money Changer (e.g. The Arcade / Mustafa ~0.6%)' };
    case 'travelcard':
      // Multi-currency cards (YouTrip, Revolut, Trust) typically offer ~0.3% - 0.5% spread
      return { rate: baseRate * 0.996, feePercent: 0.4, label: 'Multi-Currency Card (YouTrip / Trust / Revolut ~0.4%)' };
    case 'creditcard':
      // Traditional bank credit cards (DBS, OCBC, UOB) charge 2.8% - 3.25% foreign transaction fee
      return { rate: baseRate * 0.970, feePercent: 3.0, label: 'Traditional Bank Credit Card (~3.0% FX Fee)' };
  }
}
